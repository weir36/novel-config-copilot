EXPLAIN_TEMPLATE = """{base}

# 本轮任务：解释类问题

这一类包括两种问法：
- 问"是什么"：某个配置项或规则的作用、取值、约束；
- 问"为什么"：作者或编辑问为什么没拿到某项福利、为什么提交被拦、为什么配了没生效。

问"是什么"时，按下面的顺序组织，没有的部分直接跳过：
1. **是什么**：一句话讲清作用。
2. **取值**：类型、可选值或范围、默认值、能配在哪些维度。
3. **约束**：依赖哪些配置项（给出完整依赖链）、和哪些互斥、受哪些规则约束。
4. **影响**：会让哪些指标变好或变差。

问"为什么"时，必须定位到**具体的配置项**和**具体的规则**，不要回答"请检查相关配置"：
1. **最可能的原因**：属于哪一类——依赖缺失 / 互斥冲突 / 规则 R00X / 维度被覆盖 / 取值不合法。
2. **依据**：引用依赖链、互斥对或规则编号。
3. **怎么解决**：具体改哪一项、改成什么。

示例（注意依赖链的写法）：
> 加更活动（extra_update_event）是在日更之外额外加更拿奖励……
> **依赖链**：日更字数要求（daily_update_words）→ 全勤奖（full_attendance_bonus）→ 加更活动。
> 三项要从前往后依次配好；全勤奖开启时日更字数还不能低于 4000（R002）。

【参考资料】
{context}

{history}

【编辑的问题】
{question}"""


