TEMPLATES: dict[Intent, str] = {
    Intent.EXPLAIN: EXPLAIN_TEMPLATE,
    Intent.RECOMMEND: RECOMMEND_TEMPLATE,
    Intent.OPTIMIZE: OPTIMIZE_TEMPLATE,
}


def build_prompt(
    intent: Intent, question: str, context: str, history: str = "", current_plan: str = ""
) -> list[dict[str, str]]:
    template = TEMPLATES.get(intent, EXPLAIN_TEMPLATE)
    history_block = f"【历史对话】\n{history}" if history else ""
    content = template.format(
        base=BASE_SYSTEM,
        context=context or "（本轮未检索到相关资料）",
        history=history_block,
        question=question,
        current_plan=current_plan or "（工作区暂无配置方案）",
    )
    # 整段塞进 system 而不是拆 system/user：
    # 参考资料和任务约束放在 system 里，模型对它们的遵循度明显更高，
    # 也更不容易被用户输入里的注入内容覆盖掉
    return [
        {"role": "system", "content": content},
        {"role": "user", "content": question},
    ]


