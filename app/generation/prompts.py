"""提示词模版。

按意图分模版，不是为了"看起来分了类"，是因为三类问题的**失败模式完全不同**：

  - explain 的失败模式是编造取值范围和依赖关系，或者"为什么没生效"只给一句"请检查配置"
    → 模版强制"只用给定资料"，原因类问题必须定位到具体配置项和规则编号
  - recommend 的失败模式是给出违反互斥/规则的组合 → 模版强制先列约束再给方案
  - optimize 的失败模式是把编辑没让动的配置项也改了 → 模版强制显式列出"改了哪些、没动哪些"

每个模版都带 1 个示例，示例里放的是新编辑最常踩的坑。
"""
